export function questionHelp(answer: Pick<Answer, 'question' | 'section'>): string[] {
  const text = `${answer.question} ${answer.section}`;
  const scopes: string[] = [];
  const scopeThree = /scope[\s-]*3|스코프\s*3/i.test(text);
  if (/scope[\s-]*1|스코프\s*1|직접\s*배출/i.test(text)) {
    scopes.push(
      '직접 배출(Scope 1)은 회사가 직접 운영하는 보일러·차량 등에서 연료를 쓰며 배출한 온실가스예요. 연료 사용 내역 등을 확인해요.',
    );
  }
  if (
    /scope[\s-]*2|스코프\s*2|scope\s*1\s*(?:[+&/,]|및|과)\s*2/i.test(text) ||
    (!scopeThree && /간접\s*배출/i.test(text))
  ) {
    scopes.push(
      '간접 배출 중 Scope 2는 회사가 구매한 전기·열 등을 만드는 과정에서 다른 곳에서 발생한 온실가스예요. 전기·열 사용 내역 등이 필요해요.',
    );
  }
  if (scopeThree) {
    scopes.push(
      'Scope 3는 직접 배출과 구매한 에너지 외에, 구매·운송·제품 사용·폐기 등 회사와 연결된 활동에서 발생하는 간접 온실가스예요. 어떤 활동까지 포함할지 먼저 확인해야 해요.',
    );
  }
  if (scopes.length) return scopes;
  return [
    TOPICS.find(([pattern]) => pattern.test(text))?.[1] ||
      '회사가 이 일을 실제로 어떻게 운영하는지와, 그 내용을 확인할 서류가 있는지 묻는 질문이에요. 모르는 내용은 메모로 남기고 회사의 관련 담당자에게 확인해 보세요.',
  ];
}
